/* Builds the published index.html (static slides with the data baked in).
 * Used by the setup page ("Download index.html") and by build.js (Node). */
(function (root) {
  'use strict';

  const escHtml = (s) => String(s == null ? '' : s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  const safeJson = (o) => JSON.stringify(o).replace(/</g, '\\u003c').replace(new RegExp(String.fromCharCode(0x2028), 'g'), '\\u2028').replace(new RegExp(String.fromCharCode(0x2029), 'g'), '\\u2029');

  /** deck: { cfg, resolved, images }  (images: key -> data URL or relative path) */
  function buildIndex(deck) {
    const title = deck.cfg.title || 'Kabab Showdown';
    return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escHtml(title)}</title>
<meta name="description" content="${escHtml(deck.cfg.subtitle || '')}">
<!-- Generated by Kabab Showdown Studio (setup.html / build.js). Do not edit by hand: change the data and rebuild. -->
<link rel="stylesheet" href="css/style.css">
</head>
<body class="presenting">
  <div id="present" class="no-exit">
    <div id="stage" class="stage">
      <div class="bg"><i class="orb o1"></i><i class="orb o2"></i><i class="orb o3"></i><i class="grain"></i></div>
      <div id="slides"></div>
      <canvas id="confetti"></canvas>
    </div>
    <div class="ui-bar">
      <button data-act="prev" title="Back (←)">‹</button>
      <span id="counter"></span>
      <button data-act="next" title="Next (→)">›</button>
      <button data-act="whatif" title="What if… exclude guests (X)">🧮 What if…</button>
      <button data-act="fs" title="Fullscreen (F)">⛶</button>
    </div>
    <nav id="dots"></nav>
    <div id="progress"><i></i></div>
  </div>
  <noscript><p style="color:#fff;padding:2rem">This presentation needs JavaScript.</p></noscript>
  <script id="ka-deck" type="application/json">${safeJson(deck)}</script>
  <script src="js/analytics.js"></script>
  <script src="js/slides.js"></script>
  <script src="js/present.js"></script>
  <script>
    (function () {
      var d = JSON.parse(document.getElementById('ka-deck').textContent);
      KAPresent.start({ cfg: d.cfg, images: d.images, resolved: d.resolved, onExit: null });
    })();
  </script>
</body>
</html>
`;
  }

  const KAE = { buildIndex };
  if (typeof module !== 'undefined' && module.exports) module.exports = KAE; else root.KAExport = KAE;
})(typeof window !== 'undefined' ? window : globalThis);
